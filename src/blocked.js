// Recognise bot-protection responses (Cloudflare challenges and block pages, Vercel's checkpoint) so they are
// reported as "Blocked" — the monitor can't see the site — instead of counting as the site being down.
const MARKERS = [
  /Attention Required! \| Cloudflare/i,
  /<title>Just a moment\.\.\.<\/title>/i,
  /challenge-platform/i,
  /cf-chl-/i,
  /cf-error-details/i,
  /Cloudflare Ray ID/i,
  /Sorry, you have been blocked/i,
  /^error code: 10\d\d\b/im, // Cloudflare plain-text errors: 1006/1010/1015 (rate limited)/1020 (WAF rule)
  /Vercel Security Checkpoint/i,
];

export function isBotBlock(res, body = '') {
  if (res.headers.get('cf-mitigated') || res.headers.get('x-vercel-mitigated')) return true;
  if (![403, 429, 503].includes(res.status)) return false;
  if (MARKERS.some((re) => re.test(body))) return true;
  // a bare 403/429 generated by Cloudflare's edge (WAF rule, Bot Fight Mode, rate limit) — not the site's own page
  return /cloudflare/i.test(res.headers.get('server') || '') && res.status !== 503 && body.trim().length < 600;
}
